/* ---------------- Markdown renderer ---------------- */
export function toMarkdown(d: Doc): string {
  const L: string[] = [];
  L.push(`# ${d.title}`, `**${d.kicker}**`, '', `> ${d.subtitle}`, '');
  const blocks = (bs: Block[]) => { for (const b of bs) {
    if ('h3' in b) L.push(`### ${b.h3}`, '');
    else if ('p' in b) L.push(b.p, '');
    else if ('ol' in b) { b.ol.forEach((x, i) => L.push(`${i + 1}. ${x}`)); L.push(''); }
    else if ('ul' in b) { b.ul.forEach((x) => L.push(`- ${x}`)); L.push(''); }
    else if ('check' in b) { b.check.forEach((x) => L.push(`- [ ] ${x}`)); L.push(''); }
    else if ('table' in b) { L.push(`| ${b.table.head.join(' | ')} |`, `|${b.table.head.map(() => '---').join('|')}|`); b.table.rows.forEach((r) => L.push(`| ${r.map((c) => c.replace(/\|/g, '/').replace(/\n/g, ' ')).join(' | ')} |`)); L.push(''); }
    else if ('note' in b) L.push(`> ${b.tone === 'warn' ? '**Ojo.** ' : b.tone === 'tip' ? '**Truco.** ' : b.tone === 'secret' ? '**Confidencial.** ' : ''}${b.note}`, '');
    else if ('example' in b) L.push(`> **Ejemplo.** ${b.example}`, '');
  } };
  blocks(d.intro);
  L.push('## Índice', '');
  d.sections.forEach((s, i) => L.push(`${i + 1}. [${s.title}](#${s.id})`));
  L.push('');
  d.sections.forEach((s, i) => { L.push(`<a id="${s.id}"></a>`, '', `## ${i + 1}. ${s.title}`, ''); blocks(s.blocks); });
  L.push('---', `_${d.footer}_`, '');
  return L.join('\n');
}

