/* ---------------- content model ---------------- */
export type Block =
  | { h3: string }
  | { p: string }
  | { ol: string[] }
  | { ul: string[] }
  | { check: string[] }
  | { table: { head: string[]; rows: string[][] } }
  | { note: string; tone?: 'tip' | 'warn' | 'secret' }
  | { example: string };
export interface Section { id: string; title: string; blocks: Block[] }
export interface Doc { title: string; kicker: string; subtitle: string; secret: boolean; intro: Block[]; sections: Section[]; footer: string }

/* ---------------- helpers ---------------- */
const pct = (n: number) => `${Math.round(n * 100)} %`;
const ep2 = (n: number) => String(n).padStart(2, '0');
const names = (ids: string[]) => ids.map((id) => challengeById(id)?.name ?? id);
const boxOf = (prizeId: string) => BOXES.find((b) => b.entries.some((e) => e.prizeId === prizeId))!;
const chance = (prizeId: string) => { const b = boxOf(prizeId); const tot = b.entries.reduce((a, e) => a + e.weight, 0); return b.entries.find((e) => e.prizeId === prizeId)!.weight / tot; };
const howToGet = (p: Prize) => { const b = boxOf(p.id); return `${b.name} (${pct(chance(p.id))}), desde el episodio ${ep2(b.unlockEpisode)}`; };
const flags = (p: Prize) => [p.unique ? 'único' : '', PRIZE_FOR[p.id] ? `solo para ${PRIZE_FOR[p.id] === 'tatiana' ? 'Tatiana' : 'Gabriel'}` : ''].filter(Boolean).join(', ');
const prizeRows = (list: Prize[]) => list.map((p) => [`**${p.title}**`, p.text, howToGet(p), flags(p) || '—']);
const ex = challengeById('p-cocktail')!;
const fin = challengeById('h-triathlon')!;
const wheelRow = (id: string) => { const w = WHEELS.find((x) => x.id === id)!; return w; };

